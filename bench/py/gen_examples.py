"""Writes py/gen/examples_bench.py: the repo's tests/compare/examples_py.py (the 24 examples as
Python build123d functions) without its metrics import and its main(), so that loading it
imports build123d and nothing else.

    python -I gen_examples.py <repo> <out.py>
"""

import sys

repo, out = sys.argv[1], sys.argv[2]
src = open(f"{repo}/tests/compare/examples_py.py", encoding="utf-8").read()
src = src.replace("from cases_py import metrics\n", "")
cut = src.index("\ndef main():")
src = src[:cut] + "\n"
with open(out, "w", encoding="utf-8") as f:
    f.write("# Generated by libbench/py/gen_examples.py from tests/compare/examples_py.py\n" + src)
