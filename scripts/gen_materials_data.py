"""Generate bd_materials' catalog for the C++ port from the installed package:

- include/build123d/material_catalog.hpp: one namespace per catalog module (metals, plastics,
  resins, glass, wood, paper, textile) with its grade enums, grade tables, ALL_<module> list,
  family functions and custom_<kind> function.
- src/material_catalog.inc: the grades' data, the material classes' fields, the definitions of
  the declared functions and tables, and the registry (every name resolve() accepts).

The script checks every family and custom function against the templates the C++ code
implements, so a function doing anything else stops the generation.

    python scripts/gen_materials_data.py .
"""

import ast
import dataclasses
import enum
import inspect
import math
import os
import sys
from importlib.metadata import version

from bd_materials import core, materials, registry

MODULES = ("metals", "plastics", "resins", "glass", "wood", "paper", "textile")

# The C++ option struct for each family-function signature (after `grade`): the parameter
# names with their defaults, and the FinishedMaterial keywords the function passes on.
OPTION_SHAPES = {
    "MetalOptions": (
        [("finish", None), ("process", None), ("density", None)],
        ["process"],
    ),
    "PolymerOptions": (
        [("color", None), ("finish", None), ("process", None), ("density", None)],
        ["color", "process"],
    ),
    "TransparentOptions": (
        [("color", None), ("thickness_mm", None), ("opacity", None), ("roughness", None),
         ("finish", None), ("process", None), ("density", None)],
        ["color", "thickness_mm", "opacity", "roughness", "process"],
    ),
    "PaperOptions": (
        [("color", "white"), ("finish", None), ("process", None), ("density", None),
         ("scale", (1.0, 1.0)), ("rotation", 0.0)],
        ["color", "process", "scale", "rotation"],
    ),
    "TexturedOptions": (
        [("finish", None), ("process", None), ("density", None), ("scale", (1.0, 1.0)),
         ("rotation", 0.0)],
        ["process", "scale", "rotation"],
    ),
    "TextileOptions": (
        [("color", None), ("finish", None), ("process", None), ("density", None),
         ("scale", (1.0, 1.0)), ("rotation", 0.0)],
        ["color", "process", "scale", "rotation"],
    ),
}

# C++ types of the custom_<kind> keyword parameters
CUSTOM_TYPES = {
    "family": "std::string",
    "transparent": "bool",
    "hardness_scale": "std::string",
    "color": "std::optional<ColorSpec>",
    "thickness_mm": "std::optional<double>",
    "opacity": "std::optional<double>",
    "roughness": "std::optional<double>",
    "scale": "std::pair<double, double>",
    "rotation": "double",
    "finish": "std::optional<FinishSpec>",
    "process": "std::optional<ProcessSpec>",
    "pbr": "std::shared_ptr<const PbrProperties>",
}


def cstr(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def body_of(fn):
    tree = ast.parse(inspect.getsource(fn)).body[0]
    return [s for s in tree.body if not (isinstance(s, ast.Expr) and isinstance(s.value, ast.Constant))]


def fail(msg):
    raise SystemExit(msg)


def num(value):
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        fail(f"not a number: {value!r}")
    return repr(float(value))


def default_cpp(value):
    if value is None:
        return "{}"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return cstr(value)
    if isinstance(value, float):
        return repr(value)
    if isinstance(value, tuple):
        return "{" + ", ".join(repr(float(v)) for v in value) + "}"
    fail(f"no C++ default for {value!r}")


def module_of(mod):
    return mod.__name__.split(".")[-1]


def main(root):
    header = []
    inc = []
    hpp_path = os.path.join(root, "include", "build123d", "material_catalog.hpp")
    inc_path = os.path.join(root, "src", "material_catalog.inc")
    banner = f"Generated by scripts/gen_materials_data.py from bd_materials {version('bd_materials')}. Don't edit."

    # ---- the material classes -------------------------------------------------------------
    classes = [core.RangeMaterial, core.SolidMaterial, core.PolymerMaterial, core.ArealMaterial]
    for mod in registry._catalog_modules():
        for attr, val in vars(mod).items():
            if isinstance(val, type) and issubclass(val, core.RangeMaterial) and val.__module__ == mod.__name__:
                classes.append(val)
    inc.append(f"// {banner}")
    inc.append("// clang-format off")
    inc.append("#ifdef B3D_MATERIAL_CLASSES")
    for cls in classes:
        fields = [f.name for f in dataclasses.fields(cls)]
        inc.append(f"{{{cstr(cls.__name__)}, {cstr(cls.category)}, {cstr(' '.join(fields))}}},")
    inc.append("#endif")

    # ---- the grades -----------------------------------------------------------------------
    inc.append("#ifdef B3D_MATERIAL_GRADES")
    grade_rows = {}
    for mod in registry._catalog_modules():
        for attr, table in vars(mod).items():
            if not attr.endswith("_MATERIALS") or not isinstance(table, dict):
                continue
            for grade, m in table.items():
                props = []
                hardness_scale = "nullptr"
                for f in dataclasses.fields(m):
                    if f.name in ("name", "density", "family", "transparent"):
                        continue
                    v = getattr(m, f.name)
                    if f.name == "hardness_scale":
                        hardness_scale = cstr(v)
                    elif v is None:
                        props.append(f"{f.name}=None")
                    elif isinstance(v, core.Range):
                        lo = "nan" if math.isnan(v.min) else num(v.min)
                        hi = "nan" if math.isnan(v.max) else num(v.max)
                        props.append(f"{f.name}={lo},{hi}")
                    else:
                        fail(f"{m.name}.{f.name}: unexpected value {v!r}")
                row = (
                    f"{{{cstr(module_of(mod))}, {cstr(type(grade).__name__)}, {cstr(grade.name)}, {grade.value}, "
                    f"{cstr(type(m).__name__)}, {cstr(m.name)}, {num(m.density)}, "
                    f"{cstr(m.family) if m.family is not None else 'nullptr'}, {'true' if m.transparent else 'false'}, "
                    f"{hardness_scale}, {cstr(' '.join(props))}}},"
                )
                inc.append(row)
                grade_rows[(type(grade), grade)] = m
    inc.append("#endif")

    # ---- the family functions -------------------------------------------------------------
    header += [
        f"// {banner}",
        "//",
        "// bd_materials' catalog: one namespace per module of bd_materials.materials, each with its",
        "// grade enums, grade tables (<FAMILY>_MATERIALS), family functions (each a FinishedMaterial",
        "// of a grade), ALL_<MODULE> and custom_<kind>(). For example:",
        "//",
        "//   part.material = metals::aluminum(metals::Alu::G7075_T6, {.finish = finishes::anodize(\"black\")});",
        "//   part.material = plastics::pla({.color = \"orange\", .process = processes::fdm()});",
        "//   part.material = wood::oak({.scale = {2, 2}});",
        "#pragma once",
        "",
        "#include <map>",
        "#include <memory>",
        "#include <optional>",
        "#include <string>",
        "#include <utility>",
        "#include <vector>",
        "",
        "#include \"build123d/materials.hpp\"",
        "",
        "namespace build123d {",
    ]
    defs = ["#ifdef B3D_MATERIAL_DEFINITIONS"]
    invokers = []
    all_rows = []
    by_enum = registry._functions_by_grade_enum()
    for mod in registry._catalog_modules():
        mname = module_of(mod)
        header += ["", f"namespace {mname} {{", ""]
        for attr, val in vars(mod).items():
            if attr.startswith("_"):
                continue
            if isinstance(val, type) and issubclass(val, enum.Enum) and val.__module__ == mod.__name__:
                members = ", ".join(f"{m.name} = {m.value}" for m in val)
                header.append(f"/// bd_materials.materials.{mname}.{attr}: the grades of {by_enum[val].__name__}().")
                header.append(f"enum class {attr} {{ {members} }};")
            elif isinstance(val, dict) and attr.endswith("_MATERIALS"):
                etype = type(next(iter(val)))
                header.append(f"/// The {etype.__name__} grades' materials.")
                header.append(f"extern const std::map<{etype.__name__}, RangeMaterial> {attr};")
                entries = ", ".join(
                    f"{{{etype.__name__}::{g.name}, detail::catalog_grade({cstr(mname)}, {cstr(etype.__name__)}, {g.value})}}"
                    for g in val)
                defs.append(f"const std::map<{mname}::{etype.__name__}, RangeMaterial> {mname}::{attr} = {{{entries}}};")
            elif isinstance(val, tuple) and attr.startswith("ALL_"):
                header.append(f"/// Every material of the module, in bd_materials' order.")
                header.append(f"extern const std::vector<RangeMaterial> {attr};")
                items = []
                for m in val:
                    key = next(k for k, v in grade_rows.items() if v is m)
                    items.append(f"detail::catalog_grade({cstr(mname)}, {cstr(key[0].__name__)}, {key[1].value})")
                defs.append(f"const std::vector<RangeMaterial> {mname}::{attr} = {{{', '.join(items)}}};")
            elif inspect.isfunction(val) and val.__module__ == mod.__name__ and attr.startswith("custom_"):
                header += custom_function(mname, attr, val, defs)
            elif inspect.isfunction(val) and val.__module__ == mod.__name__:
                header += family_function(mname, attr, val, defs, invokers)
            else:
                continue
            header.append("")
        header.append(f"}}  // namespace {mname}")
    header += [
        "",
        "/// bd_materials.materials.ALL_MATERIALS: every catalog material, module by module.",
        "extern const std::vector<RangeMaterial> ALL_MATERIALS;",
        "",
        "}  // namespace build123d",
    ]
    for m in materials.ALL_MATERIALS:
        (etype, grade), = [k for k, v in grade_rows.items() if v is m]
        mod = sys.modules[etype.__module__]
        all_rows.append(f"{{{cstr(module_of(mod))}, {cstr(etype.__name__)}, {grade.value}}},")
    defs.append("const std::vector<RangeMaterial> ALL_MATERIALS = detail::all_materials();")
    defs.append("#endif")
    inc += defs
    inc.append("#ifdef B3D_MATERIAL_ALL")
    inc += all_rows
    inc.append("#endif")

    # ---- the registry ---------------------------------------------------------------------
    inc.append("#ifdef B3D_MATERIAL_INVOKERS")
    inc += invokers
    inc.append("#endif")
    inc.append("#ifdef B3D_MATERIAL_REGISTRY")
    fn_names = {fn: name for name, fn in registry._family_functions()}
    for key, entry in registry._REGISTRY.items():
        if hasattr(entry, "func"):
            fn, (grade,) = entry.func, entry.args
            inc.append(f"{{{cstr(key)}, {cstr(fn_names[fn])}, {grade.value}}},")
        else:
            inc.append(f"{{{cstr(key)}, {cstr(fn_names[entry])}, 0}},")
    inc.append("#endif")
    inc.append("// clang-format on")

    with open(hpp_path, "w", encoding="utf-8") as f:
        f.write("\n".join(header) + "\n")
    with open(inc_path, "w", encoding="utf-8") as f:
        f.write("\n".join(inc) + "\n")
    print(len(grade_rows), "grades,", len(invokers), "family functions,", len(registry._REGISTRY), "names")


def family_function(mname, name, fn, defs, invokers):
    params = list(inspect.signature(fn).parameters.values())
    body = body_of(fn)
    if len(body) != 1 or not isinstance(body[0], ast.Return):
        fail(f"{mname}.{name}: not a single return")
    call = body[0].value
    cname = ast.unparse(call.func)
    has_grade = params and params[0].name == "grade"
    rest = params[1:] if has_grade else params
    shape = [(p.name, p.default) for p in rest]
    for p in rest:
        if p.kind != p.POSITIONAL_OR_KEYWORD:
            fail(f"{mname}.{name}: {p.name} isn't positional-or-keyword")
    struct = next((s for s, (ps, _) in OPTION_SHAPES.items() if ps == shape), None)
    if struct is None:
        fail(f"{mname}.{name}: unknown signature {shape}")
    lines = []
    if cname == "FinishedMaterial":
        # FinishedMaterial(with_density(<TABLE>[grade], density), finish, <keywords>)
        if not has_grade:
            fail(f"{mname}.{name}: FinishedMaterial without a grade")
        etype = type(params[0].default).__name__
        first = call.args[0]
        want_first = f"with_density({etype_table(fn, etype)}[grade], density)"
        if ast.unparse(first) != want_first or len(call.args) != 2 or ast.unparse(call.args[1]) != "finish":
            fail(f"{mname}.{name}: unexpected FinishedMaterial arguments {ast.unparse(call)}")
        keywords = [(k.arg, ast.unparse(k.value)) for k in call.keywords]
        if sorted(keywords) != sorted((k, k) for k in OPTION_SHAPES[struct][1]):
            fail(f"{mname}.{name}: passes {keywords}, expected {OPTION_SHAPES[struct][1]}")
        default = params[0].default
        lines.append(f"/// {mname}.{name}(grade={etype}.{default.name}, ...)")
        lines.append(f"FinishedMaterial {name}({etype} grade = {etype}::{default.name}, const {struct}& options = {{}});")
        lines.append(f"FinishedMaterial {name}(const {struct}& options);")
        defs.append(
            f"FinishedMaterial {mname}::{name}({etype} grade, const {struct}& options) {{ "
            f"return detail::family_material(detail::catalog_grade({cstr(mname)}, {cstr(etype)}, static_cast<int>(grade)), options); }}")
        defs.append(
            f"FinishedMaterial {mname}::{name}(const {struct}& options) {{ return {name}({etype}::{default.name}, options); }}")
        invokers.append(
            f"{{{cstr(name)}, [](int grade, const registry::MaterialArgs& args) {{ "
            f"const auto options = detail::options_from<{struct}>(args, {cstr(name)}); "
            f"return grade != 0 ? {mname}::{name}(static_cast<{mname}::{etype}>(grade), options) : {mname}::{name}(options); }}}},")
    else:
        # <family>(<Enum>.<MEMBER>, finish, process, density, scale, rotation)
        target = getattr(sys.modules[fn.__module__], cname)
        tparams = list(inspect.signature(target).parameters)
        if has_grade or [ast.unparse(a) for a in call.args[1:]] != [p.name for p in rest] or call.keywords:
            fail(f"{mname}.{name}: unexpected wrapper {ast.unparse(call)}")
        if tparams[1:] != [p.name for p in rest]:
            fail(f"{mname}.{name}: wrapper parameters differ from {cname}")
        member = ast.unparse(call.args[0])
        etype, mem = member.split(".")
        lines.append(f"/// {mname}.{name}(...) = {cname}({member}, ...)")
        lines.append(f"FinishedMaterial {name}(const {struct}& options = {{}});")
        defs.append(f"FinishedMaterial {mname}::{name}(const {struct}& options) {{ return {cname}({etype}::{mem}, options); }}")
        invokers.append(
            f"{{{cstr(name)}, [](int, const registry::MaterialArgs& args) {{ "
            f"return {mname}::{name}(detail::options_from<{struct}>(args, {cstr(name)})); }}}},")
    return lines


def etype_table(fn, etype):
    mod = sys.modules[fn.__module__]
    names = [a for a, v in vars(mod).items() if a.endswith("_MATERIALS") and isinstance(v, dict)
             and type(next(iter(v))).__name__ == etype]
    if len(names) != 1:
        fail(f"no single table for {etype}")
    return names[0]


def custom_function(mname, name, fn, defs):
    params = list(inspect.signature(fn).parameters.values())
    if [p.name for p in params[:2]] != ["name", "density"] or any(p.kind != p.KEYWORD_ONLY for p in params[2:]):
        fail(f"{mname}.{name}: unexpected signature")
    body = body_of(fn)
    call = body[0].value
    if len(body) != 1 or ast.unparse(call.func) != "FinishedMaterial":
        fail(f"{mname}.{name}: not a single FinishedMaterial")
    inner = call.args[0]
    cls = getattr(sys.modules[fn.__module__], ast.unparse(inner.func))
    fields = {f.name for f in dataclasses.fields(cls)}
    field_args = {}
    for k in inner.keywords:
        src = ast.unparse(k.value)
        if src == k.arg:
            field_args[k.arg] = "plain"
        elif src == f"as_range({k.arg})":
            field_args[k.arg] = "range"
        else:
            fail(f"{mname}.{name}: {k.arg}={src}")
    if set(field_args) != fields:
        fail(f"{mname}.{name}: doesn't set every field of {cls.__name__}")
    if [ast.unparse(a) for a in call.args[1:]] != ["finish"]:
        fail(f"{mname}.{name}: unexpected FinishedMaterial arguments")
    passed = [k.arg for k in call.keywords]
    if any(ast.unparse(k.value) != k.arg for k in call.keywords):
        fail(f"{mname}.{name}: renamed FinishedMaterial keywords")
    struct = "Custom" + name[len("custom_"):].capitalize() + "Options"
    lines = [f"/// The keyword arguments of {mname}.{name}(name, density, ...), in Python's order.",
             f"struct {struct} {{"]
    for p in params[2:]:
        if p.name in CUSTOM_TYPES:
            ctype = CUSTOM_TYPES[p.name]
        elif field_args.get(p.name) == "range":
            ctype = "std::optional<Range>"
        else:
            fail(f"{mname}.{name}: no C++ type for {p.name}")
        lines.append(f"    {ctype} {p.name} = {default_cpp(p.default)};" if p.default is not None
                     else f"    {ctype} {p.name}{{}};")
    lines.append("};")
    lines.append(f"/// {mname}.{name}: a {cls.__name__} of your own.")
    lines.append(f"FinishedMaterial {name}(const std::string& name, double density, const {struct}& options = {{}});")
    sets = [f"m.kind = {cstr(cls.__name__)};", f"m.category = {cstr(cls.category)};", "m.name = name;",
            "m.density = density;"]
    for p in params[2:]:
        if p.name in field_args:
            sets.append(f"m.{p.name} = options.{p.name};")
    kw = ", ".join(f".{k} = options.{k}" for k in ["color", "thickness_mm", "opacity", "roughness", "scale",
                                                   "rotation", "process", "pbr"] if k in passed)
    defs.append(
        f"FinishedMaterial {mname}::{name}(const std::string& name, double density, const {struct}& options) {{ "
        f"RangeMaterial m; {' '.join(sets)} return FinishedMaterial(std::move(m), options.finish, {{{kw}}}); }}")
    return lines


if __name__ == "__main__":
    main(sys.argv[1])
