"""Generate src/dxf_codepages.inc: the single-byte Windows code pages ezdxf decodes pre-R2007
DXF files with ($DWGCODEPAGE "ANSI_xxxx"), as tables of the code points of bytes 0x80-0xFF
(0 where Python's codec has no character), for import_dxf.

    python scripts/gen_dxf_codepages.py src/dxf_codepages.inc
"""

import sys

CODEPAGES = ["874", "1250", "1251", "1252", "1253", "1254", "1255", "1256", "1257", "1258"]

lines = ["// Generated by scripts/gen_dxf_codepages.py from Python's codecs. Don't edit.", "// clang-format off"]
for cp in CODEPAGES:
    values = []
    for b in range(0x80, 0x100):
        try:
            values.append(ord(bytes([b]).decode("cp" + cp)))
        except UnicodeDecodeError:
            values.append(0)
    lines.append('{"%s", {%s}},' % (cp, ", ".join("0x%X" % v for v in values)))
lines.append("// clang-format on")
with open(sys.argv[1], "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
