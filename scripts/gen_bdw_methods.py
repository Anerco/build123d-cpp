"""Generate the method tables of bd_warehouse's method_exists for the C++ port.

bd_warehouse asks whether a class has a method with method_exists(cls, method) (fastener.py) and
Bearing.method_exists(self, method) (bearing.py): hasattr(cls, method) and callable. C++ has no
class objects to ask, so this script lists, for every public class of those modules, the callable
attributes that bd_warehouse's classes define (inherited ones included, build123d's and Python's
own left out) and writes them to src/bd_warehouse/methods.inc.

    python scripts/gen_bdw_methods.py .
"""

import inspect
import os
import sys
from importlib.metadata import version

import bd_warehouse.bearing
import bd_warehouse.fastener

MODULES = [bd_warehouse.fastener, bd_warehouse.bearing]


def bdw_methods(cls) -> list[str]:
    """The callable attributes of cls defined in a bd_warehouse class of its MRO."""
    names = []
    for name in dir(cls):
        if name.startswith("__"):
            continue
        owner = next((c for c in cls.__mro__ if name in c.__dict__), None)
        if owner is None or not owner.__module__.startswith("bd_warehouse"):
            continue
        if callable(getattr(cls, name)):
            names.append(name)
    return sorted(names)


def main(root: str) -> None:
    classes = {}
    for module in MODULES:
        for name, cls in inspect.getmembers(module, inspect.isclass):
            if cls.__module__ == module.__name__ and not name.startswith("_"):
                classes[name] = cls
    out = [
        f"// Generated by scripts/gen_bdw_methods.py from bd_warehouse {version('bd_warehouse')}; do not edit.",
        "// The methods bd_warehouse's classes define, by class name (see method_exists).",
        "",
        "const std::map<std::string, std::set<std::string>> kClassMethods = {",
    ]
    for name in sorted(classes):
        methods = bdw_methods(classes[name])
        out.append(f'    {{"{name}",')
        out.append("     {" + ", ".join(f'"{m}"' for m in methods) + "}},")
    out.append("};")
    out.append("")
    target = os.path.join(root, "src", "bd_warehouse", "methods.inc")
    with open(target, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(out))
    print(f"wrote {target}: {len(classes)} classes")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
