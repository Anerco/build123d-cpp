"""Generate the data of the PBR material port from the installed Python packages:

- src/pbr_presets.inc: threejs_materials' preset factories (pbr_properties/*.py), each a
  PbrProperties.from_dict(...) literal followed by the same optional color / roughness /
  thickness overrides and texture scaling. The script checks every factory against that template,
  so a factory doing anything else stops the generation.
- src/pil_colormap.inc: PIL.ImageColor.colormap (the color names getrgb accepts).
- src/css3_hex.inc: webcolors' CSS3 names (webcolors.name_to_hex).

    python scripts/gen_pbr_data.py src
"""

import ast
import importlib
import inspect
import json
import os
import sys
from importlib.metadata import version

import webcolors
from PIL import ImageColor

MODULES = ("coats", "glass", "metal", "paper", "plastic", "textile", "wood")


def cstr(text):
    return json.dumps(text)  # a valid C++ string literal for ASCII text


def preset_spec(module_name, mod, name):
    fn = getattr(mod, name)
    src = inspect.getsource(fn)
    tree = ast.parse(src).body[0]
    params = inspect.signature(fn).parameters
    allowed = {"color", "roughness", "thickness", "scale", "rotation"}
    if not set(params) <= allowed:
        raise SystemExit(f"{module_name}.{name}: unexpected parameters {list(params)}")
    # the PbrProperties.from_dict(...) argument
    first = tree.body[0]
    call = first.value
    assert isinstance(first, ast.Assign) and first.targets[0].id == "m", name
    assert ast.unparse(call.func) == "PbrProperties.from_dict", name
    arg = call.args[0]
    maps_dir = None
    if isinstance(arg, ast.Dict) and arg.keys and arg.keys[0] is None:
        data = ast.literal_eval(arg.values[0])
        assert len(arg.keys) == 2 and ast.literal_eval(arg.keys[1]) == "maps_dir", name
        tail = arg.values[1]
        assert ast.unparse(tail).startswith("str(_ASSETS / "), name
        maps_dir = ast.literal_eval(tail.args[0].right)
    else:
        data = ast.literal_eval(arg)
    # the rest must be the template
    expected = []
    for p in ("color", "roughness", "thickness"):
        if p in params:
            expected.append(f"if {p} is not None:\n    m = m.override({p}={p})")
    scale_default = (1.0, 1.0)
    scale_int = False
    rotation_default = 0.0
    rotation_compared = False
    fixed = True
    if "scale" in params:
        scale_default = tuple(float(v) for v in params["scale"].default)
        scale_int = all(type(v) is int for v in params["scale"].default)
        if not scale_int and not all(type(v) is float for v in params["scale"].default):
            raise SystemExit(f"{module_name}.{name}: mixed scale default")
        if type(params["rotation"].default) is not float:
            raise SystemExit(f"{module_name}.{name}: rotation default isn't a float")
        rotation_default = float(params["rotation"].default)
        rot_src = ast.unparse(tree.body[len(expected) + 1].test.values[1])
        rotation_compared = rot_src != "rotation"
        fixed = "fixed=False" not in ast.unparse(tree.body[len(expected) + 1].body[0])
        cond = f"rotation != {params['rotation'].default!r}" if rotation_compared else "rotation"
        call_args = "scale[0], scale[1], rotation=rotation" + (", fixed=False" if not fixed else "")
        expected.append(
            f"if scale != {params['scale'].default!r} or {cond}:\n    m = m.scale({call_args})"
        )
    expected.append("return m")
    got = [ast.dump(s) for s in tree.body[1:]]
    want = [ast.dump(s) for s in ast.parse("\n".join(expected)).body]
    if got != want:
        raise SystemExit(f"{module_name}.{name} doesn't follow the factory template:\n{chr(10).join(expected)}\n---\n" + "\n".join(ast.unparse(s) for s in tree.body[1:]))
    for p in ("color", "roughness", "thickness"):
        if p in params and params[p].default is not None:
            raise SystemExit(f"{module_name}.{name}: {p} has a default")
    return (
        "{%s, %s, %s, %s, %s, %s, %s, %s, %r, %r, %s, %r, %s, %s}"
        % (
            cstr(module_name),
            cstr(name),
            "R\"PBRJSON(" + json.dumps(data) + ")PBRJSON\"",
            cstr(maps_dir) if maps_dir is not None else "nullptr",
            "true" if "color" in params else "false",
            "true" if "roughness" in params else "false",
            "true" if "thickness" in params else "false",
            "true" if "scale" in params else "false",
            scale_default[0],
            scale_default[1],
            "true" if scale_int else "false",
            rotation_default,
            "true" if rotation_compared else "false",
            "true" if fixed else "false",
        )
    )


def main(out_dir):
    lines = [
        "// Generated by scripts/gen_pbr_data.py from threejs_materials %s. Don't edit." % version("threejs_materials"),
        "// {module, name, data, maps_dir, color, roughness, thickness, scale, scale_u, scale_v,",
        "//  scale_int (the default scale is Python ints), rotation, rotation_compared, fixed}",
        "// clang-format off",
    ]
    count = 0
    for module_name in MODULES:
        mod = importlib.import_module(f"threejs_materials.pbr_properties.{module_name}")
        for name in mod.__all__:
            lines.append(preset_spec(module_name, mod, name) + ",")
            count += 1
    lines.append("// clang-format on")
    with open(os.path.join(out_dir, "pbr_presets.inc"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    lines = ["// Generated by scripts/gen_pbr_data.py from Pillow %s. Don't edit." % version("pillow"),
             "// clang-format off"]
    for name in sorted(ImageColor.colormap):
        r, g, b = ImageColor.getrgb(name)[:3]
        lines.append('{"%s", {%d, %d, %d}},' % (name, r, g, b))
    lines.append("// clang-format on")
    with open(os.path.join(out_dir, "pil_colormap.inc"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    lines = ["// Generated by scripts/gen_pbr_data.py from webcolors %s. Don't edit." % version("webcolors"),
             "// clang-format off"]
    for name in sorted(webcolors.names("css3")):
        lines.append('{"%s", "%s"},' % (name, webcolors.name_to_hex(name, "css3")))
    lines.append("// clang-format on")
    with open(os.path.join(out_dir, "css3_hex.inc"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(count, "presets")


if __name__ == "__main__":
    main(sys.argv[1])
