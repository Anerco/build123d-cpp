"""Generate src/dxf_templates.inc: the empty DXF documents ExportDXF starts from.

ExportDXF (src/export_dxf.cpp) writes DXF files without ezdxf. It starts from the document
ezdxf.new(dxfversion, setup=False) creates for each DXF version, as ezdxf saves it, and adds
the layers, line types, entities and view the exporter needs. This script captures those
documents (with ezdxf's own metadata removed) as C++ string literals:

    python scripts/gen_dxf_templates.py src/dxf_templates.inc
"""

import io
import sys

import ezdxf
from ezdxf.lldxf.tagger import ascii_tags_loader

VERSIONS = ["R12", "R2000", "R2004", "R2007", "R2010", "R2013", "R2018"]


def tags_of(version):
    doc = ezdxf.new(dxfversion=version, setup=False)
    stream = io.StringIO()
    doc.write(stream)
    return doc.dxfversion, [(t.code, t.value) for t in ascii_tags_loader(io.StringIO(stream.getvalue()))]


def records(tags):
    """Split the tags at every 0-tag."""
    out = []
    for code, value in tags:
        if code == 0:
            out.append([(code, value)])
        else:
            out[-1].append((code, value))
    return out


def strip_ezdxf_metadata(tags):
    recs = records(tags)
    meta_handles = set()
    for rec in recs:
        if rec[0] == (0, "DICTIONARY"):
            pairs = rec[1:]
            for i, (code, value) in enumerate(pairs):
                if code == 3 and value == "EZDXF_META":
                    meta_handles.add(pairs[i + 1][1])
    out = []
    for rec in recs:
        kind = rec[0][1]
        handle = next((v for c, v in rec if c == 5), None)
        owner = next((v for c, v in rec if c == 330), None)
        if kind == "APPID" and (2, "EZDXF") in rec:
            continue
        if kind == "DICTIONARY" and handle in meta_handles:
            continue
        if kind == "DICTIONARYVAR" and owner in meta_handles:
            continue
        if kind == "DICTIONARY":
            new = []
            skip = 0
            for code, value in rec:
                if skip:
                    skip -= 1
                    continue
                if code == 3 and value == "EZDXF_META":
                    skip = 1
                    continue
                new.append((code, value))
            rec = new
        if kind == "BLOCK":
            # R12 keeps the metadata as XDATA of the model space block
            new = []
            in_ezdxf_xdata = False
            for code, value in rec:
                if code == 1001:
                    in_ezdxf_xdata = value == "EZDXF"
                if in_ezdxf_xdata and code >= 1000:
                    continue
                new.append((code, value))
            rec = new
        out.extend(rec)
    # fix the APPID table count
    result = []
    for i, (code, value) in enumerate(out):
        result.append((code, value))
    return fix_table_counts(result)


def fix_table_counts(tags):
    recs = records(tags)
    out = []
    i = 0
    while i < len(recs):
        rec = recs[i]
        if rec[0] == (0, "TABLE"):
            name = next(v for c, v in rec if c == 2)
            j = i + 1
            count = 0
            while recs[j][0] != (0, "ENDTAB"):
                if recs[j][0][1] == name:
                    count += 1
                j += 1
            rec = [(c, str(count) if c == 70 else v) for c, v in rec]
        out.extend(rec)
        i += 1
    return out


def header_set(tags, name, value):
    out = []
    i = 0
    while i < len(tags):
        code, val = tags[i]
        out.append((code, val))
        if code == 9 and val == name:
            out.append((tags[i + 1][0], value))
            i += 2
            continue
        i += 1
    return out


def dxf_text(tags):
    return "".join("%3d\n%s\n" % (code, value) for code, value in tags)


def c_literal(text, chunk=8000):
    parts = []
    while text:
        piece = text[:chunk]
        text = text[chunk:]
        parts.append('R"DXF(' + piece + ')DXF"')
    return "\n".join(parts)


def main():
    out = [
        "// Generated by scripts/gen_dxf_templates.py from ezdxf %s: the documents" % ezdxf.__version__,
        "// ezdxf.new(dxfversion, setup=False) saves, without ezdxf's metadata. Don't edit.",
        "// clang-format off",
        "struct DxfTemplate {",
        "    const char* version;",
        "    const char* text;",
        "};",
        "const DxfTemplate kDxfTemplates[] = {",
    ]
    for version in VERSIONS:
        acad, tags = tags_of(version)
        tags = strip_ezdxf_metadata(tags)
        tags = header_set(tags, "$LASTSAVEDBY", "build123d")
        out.append('{"%s",\n%s},' % (acad, c_literal(dxf_text(tags))))
    out.append("};")
    out.append("// clang-format on")
    with open(sys.argv[1], "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
