"""Generate src/css3_names.inc: the CSS3 color name webcolors.rgb_to_name returns for each RGB
triplet that has one (Python build123d's str(Color) uses it), for the 3MF material names.

    python scripts/gen_css3_names.py src/css3_names.inc
"""

import sys

import webcolors

triplets = {}
for name in webcolors.names("css3"):
    rgb = tuple(webcolors.name_to_rgb(name, "css3"))
    triplets[rgb] = webcolors.rgb_to_name(rgb, "css3")
lines = ["// Generated by scripts/gen_css3_names.py from webcolors %s. Don't edit." % webcolors.__version__,
         "// clang-format off"]
for (r, g, b), name in sorted(triplets.items()):
    lines.append('{0x%02X%02X%02X, "%s"},' % (r, g, b, name))
lines.append("// clang-format on")
with open(sys.argv[1], "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
print(len(triplets))
