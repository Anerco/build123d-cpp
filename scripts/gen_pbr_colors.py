"""Generate src/pbr_colors.inc: for each material grade of the bd_materials catalog, the color
build123d's Shape.material setter gives a shape (``material.pbr.interpolate_color()``) when the
material is assigned by name, i.e. without a finish or color of its own.

    python scripts/gen_pbr_colors.py src/pbr_colors.inc
"""

import sys
from importlib.metadata import version

from bd_materials import material_names, resolve

colors = {}
for name in material_names():
    finished = resolve(name)
    color = finished.pbr.interpolate_color()
    grade = finished.material.name
    if colors.setdefault(grade, color) != color:
        raise SystemExit(f"{grade}: the catalog names of one grade give different colors")

lines = [
    "// Generated by scripts/gen_pbr_colors.py from bd_materials %s. Don't edit." % version("bd_materials"),
    "// clang-format off",
]
for grade in sorted(colors):
    lines.append('{"%s", {%s}},' % (grade, ", ".join(repr(float(v)) for v in colors[grade])))
lines.append("// clang-format on")
with open(sys.argv[1], "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
print(len(colors))
