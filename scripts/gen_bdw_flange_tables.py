"""Generate the ASME B16.5 tables of bd_warehouse's flange.py for the C++ port.

flange.py holds its tables as Python dicts (numbers, fractions as text, and "…" or "Note (8)"
where the standard has no value): drilling_class_150/300, flange_data_class_150/300,
ring_joint_facings_class_150/300 and nps_to_dn. This script writes them as C++ initializers
(each cell a bd_warehouse::Param, text in UTF-8) to src/bd_warehouse/flange_tables.inc.

    python scripts/gen_bdw_flange_tables.py .
"""

import os
import sys
from importlib.metadata import version

import bd_warehouse.flange as flange

TABLES = [
    "drilling_class_150",
    "drilling_class_300",
    "flange_data_class_150",
    "flange_data_class_300",
    "ring_joint_facings_class_150",
    "ring_joint_facings_class_300",
]


def cxx_str(text: str) -> str:
    """A C string literal of the text's UTF-8 bytes."""
    out = '"'
    for byte in text.encode("utf-8"):
        if byte in (0x22, 0x5C):  # " and backslash
            out += "\\" + chr(byte)
        elif 0x20 <= byte < 0x7F and byte != 0x3F:  # printable (not ?, no trigraphs)
            out += chr(byte)
        else:
            out += "\\%03o" % byte
    return out + '"'


def cell(value) -> str:
    if isinstance(value, bool):
        raise TypeError(f"unexpected bool {value}")
    if isinstance(value, int):
        return f"Param({value})"
    if isinstance(value, float):
        return f"Param({value!r})"
    return f"Param({cxx_str(value)})"


def main(root: str) -> None:
    out = [
        f"// Generated by scripts/gen_bdw_flange_tables.py from bd_warehouse {version('bd_warehouse')}'s",
        "// flange.py; do not edit.",
        "",
    ]
    for name in TABLES:
        out.append(f"const FlangeTable& {name}() {{")
        out.append("    static const FlangeTable table = {")
        for key, row in getattr(flange, name).items():
            out.append(f"        {{{cxx_str(key)}, {{{', '.join(cell(v) for v in row)}}}}},")
        out.append("    };")
        out.append("    return table;")
        out.append("}")
        out.append("")
    out.append("const Dict<std::string, int>& nps_to_dn() {")
    out.append("    static const Dict<std::string, int> table = {")
    for key, value in flange.nps_to_dn.items():
        out.append(f"        {{{cxx_str(key)}, {value}}},")
    out.append("    };")
    out.append("    return table;")
    out.append("}")
    out.append("")
    target = os.path.join(root, "src", "bd_warehouse", "flange_tables.inc")
    with open(target, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(out))
    print(f"wrote {target}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
