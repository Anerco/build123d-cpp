"""Embed bd_warehouse's data files (its CSV tables) in the C++ port.

Writes src/bd_warehouse/data.inc: the text of every file of the installed bd_warehouse
package's data/, data_flange/ and pipe.csv, as string literals in chunks (MSVC limits the length
of one literal), with the path the Python code opens it by ("data/...", "data_flange/...",
"pipe.csv"). bd_warehouse's readers are ported and parse this text, so the library reads nothing
from disk.

    python scripts/gen_bdw_data.py .
"""

import os
import sys
from importlib.metadata import version

import bd_warehouse

CHUNK = 8000  # bytes of source text per literal


def literal_lines(data: bytes) -> list[str]:
    """The bytes as C string literal pieces, one per line of the file."""
    pieces = []
    current = []
    for byte in data:
        if byte == 0x0A:
            current.append("\\n")
            pieces.append('"' + "".join(current) + '"')
            current = []
        elif byte in (0x22, 0x5C):  # " and backslash
            current.append("\\" + chr(byte))
        elif 0x20 <= byte < 0x7F and byte != 0x3F:  # printable (not ?, no trigraphs)
            current.append(chr(byte))
        else:
            current.append("\\%03o" % byte)  # three octal digits never run into the next char
    if current:
        pieces.append('"' + "".join(current) + '"')
    return pieces


def main(root: str) -> None:
    package = os.path.dirname(bd_warehouse.__file__)
    paths = []
    for folder in ("data", "data_flange"):
        for name in sorted(os.listdir(os.path.join(package, folder))):
            if name.endswith(".csv"):
                paths.append(f"{folder}/{name}")
    paths.append("pipe.csv")

    out = [
        f"// Generated by scripts/gen_bdw_data.py from bd_warehouse {version('bd_warehouse')}'s data files;",
        "// do not edit. Each file's text in chunks, with the path bd_warehouse opens it by.",
        "",
    ]
    table = []
    for index, path in enumerate(paths):
        with open(os.path.join(package, path), "rb") as f:
            data = f.read()
        chunks: list[list[str]] = [[]]
        size = 0
        for piece in literal_lines(data):
            if size + len(piece) > CHUNK and chunks[-1]:
                chunks.append([])
                size = 0
            chunks[-1].append(piece)
            size += len(piece)
        out.append(f"// {path} ({len(data)} bytes)")
        out.append(f"const char* const kFile{index}[] = {{")
        for chunk in chunks:
            out.append("    " + "\n    ".join(chunk) + ",")
        out.append("};")
        out.append("")
        table.append(f'    {{"{path}", kFile{index}, {len(chunks)}, {len(data)}}},')
    out.append("const EmbeddedFile kEmbeddedFiles[] = {")
    out.extend(table)
    out.append("};")
    out.append("")
    target = os.path.join(root, "src", "bd_warehouse", "data.inc")
    with open(target, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(out))
    print(f"wrote {target}: {len(paths)} files")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
